/**
 * Writes the default palette from src/palette.ts into the :root and .dark
 * blocks of src/index.css. Run after changing the palette generator.
 */
import { defaultPalette, paletteCss } from "../src/palette";

const path = "src/index.css";
let css = await Bun.file(path).text();

const generated = paletteCss(defaultPalette, {
  "--font-body": "'TikTok Sans Variable', ui-sans-serif, system-ui, sans-serif",
  "--font-display": "var(--font-body)",
  "--radius": "0.625rem",
});
const [root, dark] = generated.split(/\n(?=\.dark \{)/);

function replaceBlock(source: string, selector: string, replacement: string): string {
  const start = source.indexOf(`\n${selector} {`) + 1;
  if (start === 0) throw new Error(`Missing ${selector} block in ${path}`);
  const end = source.indexOf("\n}\n", start) + 3;
  return source.slice(0, start) + replacement.trimEnd() + "\n" + source.slice(end);
}

const note = "/* Generated by scripts/sync-theme.ts from src/palette.ts. Edit the generator, not this block. */\n";
css = css.replace(note, "");
css = replaceBlock(css, ":root", note + root);
css = replaceBlock(css, ".dark", dark);
await Bun.write(path, css);
console.log("Synced the default palette into src/index.css");
